/// The register at this address, if the chip has one there.
pub fn find(addr: u32) -> Option<(&'static str, Option<u32>)> {
    REGISTERS
        .binary_search_by_key(&addr, |r| r.0)
        .ok()
        .map(|i| (REGISTERS[i].1, REGISTERS[i].2))
}

